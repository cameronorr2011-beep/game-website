def serve(runs,port):
    root=Path(runs).resolve()
    class Handler(BaseHTTPRequestHandler):
        def do_GET(self):
            parsed=urllib.parse.urlparse(self.path)
            try:
                from .lab import handle_get
                lab=handle_get(parsed.path)
                if lab:
                    body=lab[1]
                    self.send_response(200);self.send_header('Content-Type',lab[0])
                    self.send_header('Content-Length',str(len(body)));self.end_headers()
                    self.wfile.write(body);return
                if parsed.path=='/':
                    self.send_response(200);self.send_header('Content-Type','text/html; charset=utf-8');self.end_headers();self.wfile.write(HTML.encode());return
                if parsed.path=='/api/runs':
                    result=sorted(p.parent.name for p in root.glob('*/report.json'))
                elif parsed.path=='/api/run':
                    name=urllib.parse.parse_qs(parsed.query).get('id',[''])[0]
                    directory=(root/name).resolve()
                    if directory.parent!=root or not name: raise ValueError('Invalid run identifier')
                    report=json.loads((directory/'report.json').read_text(encoding='utf-8'))
                    traces=[];label='synthetic activity'
                    if (directory/'activity.npz').exists():
                        with np.load(directory/'activity.npz',allow_pickle=False) as d:
                            for key in ['voltage_mv','excitatory','pressure']:
                                if key in d:
                                    a=d[key];stride=max(1,len(a)//1000)
                                    a=a[::stride]
                                    if a.ndim==1: a=a[:,None]
                                    traces=a[:,:8].tolist();label=key;break
                    result={'report':report,'traces':traces,'label':label}
                else:
                    self.send_error(404);return
                payload=json.dumps(result,allow_nan=False).encode()
                self.send_response(200);self.send_header('Content-Type','application/json');self.send_header('Content-Length',str(len(payload)));self.end_headers();self.wfile.write(payload)
            except (ValueError,OSError,KeyError) as error:
                self.send_error(400,str(error))

        def do_POST(self):
            parsed=urllib.parse.urlparse(self.path)
            try:
                from .lab import handle_post
                length=int(self.headers.get('Content-Length') or 0)
                payload=json.loads(self.rfile.read(length) or b'{}') if length else {}
                result=handle_post(parsed.path,payload)
                body=json.dumps(result,allow_nan=False).encode()
                self.send_response(200);self.send_header('Content-Type','application/json')
                self.send_header('Content-Length',str(len(body)));self.end_headers()
                self.wfile.write(body)
            except (ValueError,RuntimeError,OSError,KeyError) as error:
                self.send_error(400,str(error))
    server=ThreadingHTTPServer(('127.0.0.1',port),Handler)
    print(f'Neuro-ML ready at http://127.0.0.1:{port}',flush=True)
    try: server.serve_forever()
    finally: server.server_close()
