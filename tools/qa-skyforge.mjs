import assert from 'node:assert/strict';
export default async function run(page){
  const errors=[];page.on('pageerror',e=>errors.push(e.message));
  await page.waitForSelector('[data-boot="ready"]');
  await page.locator('#quality').selectOption('low');
  await page.locator('#mode').selectOption('training');
  await page.getByRole('button',{name:'Enter cockpit'}).click();
  await page.getByRole('button',{name:'Aircraft systems',exact:true}).click();
  await page.locator('[data-system="battery"]').click();
  await page.locator('[data-system="ignition"]').click();
  await page.locator('[data-system="starter"]').click();
  await page.waitForFunction(()=>document.querySelector('#systemReadouts').textContent.includes('ENGINE RUNNING'));
  await page.locator('#throttle').fill('1');
  await page.locator('[data-close="systems"]').click();
  await page.locator('#flightCanvas').focus();
  await page.keyboard.press('2');
  await page.waitForFunction(()=>Number(document.querySelector('#ias').textContent)>45,{timeout:45000});
  await page.keyboard.down('ArrowDown');
  await page.waitForFunction(()=>document.querySelector('#controlInfo').textContent.includes('AIRBORNE'),{timeout:15000});
  await page.keyboard.up('ArrowDown');
  await page.keyboard.press('f');
  await page.waitForFunction(()=>document.querySelector('#controlInfo').textContent.includes('FLAPS 10°'));
  await page.getByRole('button',{name:'Map M',exact:true}).click();
  await page.getByLabel('Waypoint east (km)').fill('4');
  await page.getByRole('button',{name:'Add waypoint',exact:true}).click();
  assert.equal(await page.locator('#routeList li').count(),2);
  assert.match(await page.locator('#mapInfo').innerText(),/km.*bearing.*ETA/);
  await page.locator('[data-close="mapPanel"]').click();
  await page.getByRole('button',{name:'01 Cockpit',exact:true}).click();
  await page.screenshot({path:'.qa/skyforge-cockpit.png'});
  await page.waitForTimeout(5000);
  const performanceText=await page.locator('#perf').innerText();
  assert.match(performanceText,/FPS.*p95.*triangles/);
  await page.getByRole('button',{name:'End / debrief',exact:true}).click();
  assert.ok(await page.locator('#reportContent').innerText());
  const downloadEvent=page.waitForEvent('download');await page.getByRole('button',{name:'Export flight JSON',exact:true}).click();
  const download=await downloadEvent;assert.equal(download.suggestedFilename(),'skyforge-flight-report.json');
  let json='';for await(const chunk of await download.createReadStream())json+=chunk.toString();const report=JSON.parse(json);
  assert.equal(report.format,'skyforge-flight-report');assert.ok(report.path.length>10);assert.ok(report.distanceMeters>100);
  await page.getByRole('button',{name:'Dispatch',exact:true}).click();
  await page.reload();await page.waitForSelector('[data-boot="ready"]');
  assert.match(await page.locator('#saveInfo').innerText(),/1 flights/);
  assert.equal(await page.locator('#mode').inputValue(),'training');
  assert.equal(errors.length,0,errors.join('\n'));
  return{startup:true,takeoff:true,flaps:true,routePlanning:true,reportExport:true,persistence:true,performance:performanceText,flightSeconds:report.durationSeconds,distanceMeters:report.distanceMeters};
}
