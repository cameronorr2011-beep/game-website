"""Deployment-index tests: exact IDs and real pair direction stay intact."""
import json
from pathlib import Path

import pytest

from neuro_ml.connectome_service import CompactConnectome


ROOT = Path(__file__).resolve().parents[1]
ASSET = ROOT / "public/data/flywire-v783.npz"
MANIFEST = ROOT / "public/data/manifest.json"


@pytest.fixture(scope="module")
def graph():
    if not ASSET.exists():
        pytest.skip("deployment asset is generated by scripts/build_connectome_asset.py")
    return CompactConnectome(ASSET, MANIFEST)


def test_deployment_asset_reconciles_manifest(graph):
    manifest = json.loads(MANIFEST.read_text(encoding="utf-8"))
    assert graph.n == manifest["counts"]["neurons"] == 139255
    assert graph.outgoing.nnz == manifest["counts"]["directed_pairs"] == 15091983
    assert int(graph.outgoing.data.sum()) == manifest["counts"]["anatomical_synapses"] == 54492922


def test_exact_id_search_and_directed_neighbors(graph):
    result = graph.search("", 1)
    neuron_id = result["results"][0]["id"]
    assert neuron_id.isdigit()
    record = graph.neuron(neuron_id, 3)
    assert record["id"] == neuron_id
    assert record["degree"]["out"] == len(graph._row(graph.outgoing, record["index"], 100, 1)) or record["degree"]["out"] > 100
    edges = graph.connections(neuron_id, "outgoing", 1, 3)["records"]
    assert edges
    assert all(edge["source"] == neuron_id for edge in edges)
    assert all(int(edge["target"]) != int(edge["source"]) or edge["synapse_count"] > 0 for edge in edges)


def test_pathway_never_invents_missing_result(graph):
    result = graph.pathway("720575940626979621", "720575940628908548", threshold=10000, max_hops=1)
    assert result["found"] is False or all(edge["synapse_count"] >= 10000 for edge in result["edges"])
